"""Declarative building blocks for katapult project migrations.

A migration is an ordered, idempotent, *scaffolding-only* transform that brings a
project generated by an older katapult release up to a newer one. Each migration is
expressed as a small list of declarative :class:`Action` objects (``AddFile`` /
``EnsureBlock``); all of the conflict-handling, dry-run, sidecar, and allowlist logic
lives in one place (:mod:`katapult.migrations.runner`), so a migration module is
essentially data.

Design invariants:

- **Scaffolding only.** Every action's destination must live under one of the
  scaffolding prefixes (``.katapult/``, ``build/``, ``mcp/``). The runner rejects any
  action that would touch user code (``lib/src``, ``nbk``, ``api/src``, ``app`` ...).
- **Idempotent.** Re-running a migration is a no-op: ``AddFile`` skips when the target
  already matches, ``EnsureBlock`` skips when its ``marker`` is already present.
- **Never clobber.** When a target was locally customized, the runner writes a sidecar
  (``<file>.katapult-new`` / ``<file>.katapult-patch``) and warns instead of
  overwriting -- unless the action is explicitly ``overwrite_ok`` (agnostic files such
  as ``.katapult/katx``).
"""

from __future__ import annotations

from dataclasses import dataclass, field

# Destination prefixes a migration is allowed to touch. Anything outside these is
# user code and must never be modified by an upgrade. `.cursor/` holds generated
# agent rules/config (not user source); `mcp/` is the dev-only MCP service.
SCAFFOLDING_PREFIXES: tuple[str, ...] = (".katapult/", ".cursor/", "build/", "mcp/")


@dataclass(frozen=True)
class AddFile:
    """Create a file in the project, sourced from the packaged project template.

    ``src_rel`` is relative to the template's ``{{cookiecutter.project_slug}}/`` root;
    ``dst_rel`` is relative to the project root. When ``templated`` is set the source is
    rendered with the reconstructed cookiecutter context before being written.

    Conflict rule (handled by the runner):

    - target missing -> create;
    - target byte-identical to what we would write -> no-op;
    - target differs and ``overwrite_ok`` -> overwrite (agnostic files, e.g. ``katx``);
    - target differs otherwise -> write ``<dst>.katapult-new`` + warn, keep original.
    """

    src_rel: str
    dst_rel: str
    templated: bool = False
    overwrite_ok: bool = False
    description: str = ""

    @property
    def target(self) -> str:
        return self.dst_rel


@dataclass(frozen=True)
class EnsureBlock:
    """Idempotently insert a text block into an existing scaffolding file.

    ``marker`` is a substring whose presence means the change is already applied (so the
    action is a no-op). Otherwise the block is inserted:

    - after the first line containing ``after`` (if given), else
    - before the first line matching the ``before_regex`` multiline pattern (if given),
    - else appended at end of file.

    If an ``after``/``before_regex`` anchor is specified but not found, the runner treats
    it as a conflict: it writes ``<dst>.katapult-patch`` with the block and warns, leaving
    the original untouched (conservative, never-clobber).
    """

    dst_rel: str
    marker: str
    block: str
    after: str | None = None
    before_regex: str | None = None
    description: str = ""

    @property
    def target(self) -> str:
        return self.dst_rel


Action = AddFile | EnsureBlock


@dataclass(frozen=True)
class Migration:
    """An ordered, named set of actions introduced by a given katapult release.

    ``id`` is the stable ordered identifier (``NNNN_slug``) recorded in a project's
    ``.katapult/manifest.json`` once applied. ``katapult_version`` is the release the
    migration shipped in (informational / reporting only).
    """

    id: str
    katapult_version: str
    description: str
    actions: list[Action] = field(default_factory=list)
